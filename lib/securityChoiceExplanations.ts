export type ChoiceVerdict = "correct" | "wrong";

export function normalizeSecurityChoiceText(choiceText: string) {
  return choiceText.replace(/\s+/g, " ").trim();
}

function isExceptionPrompt(prompt: string) {
  return /포함되지 않는|해당하지 않는|바르지 않은|옳지 않은|아닌|않은|없는|거리가 먼|틀린|잘못된/.test(
    prompt
  );
}

function hasFinalConsonant(value: string) {
  const chars = Array.from(normalizeSecurityChoiceText(value).replace(/[」"'`)\\\]]+$/g, ""));
  const last = chars[chars.length - 1];
  if (!last) return false;
  const code = last.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return false;
  return (code - 0xac00) % 28 !== 0;
}

function markedChoice(choiceText: string) {
  const text = normalizeSecurityChoiceText(choiceText);
  return `「${text}」${hasFinalConsonant(text) ? "은" : "는"}`;
}

