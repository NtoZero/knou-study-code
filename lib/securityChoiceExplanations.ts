function describeRadixChoice(choiceText: string, questionPrompt: string) {
  if (!/Radix|기수 64/.test(questionPrompt)) return undefined;

  const value = Number(normalizeSecurityChoiceText(choiceText).match(/\d+/)?.[0]);
  const bytes = Number(questionPrompt.match(/(\d+)\s*바이트/)?.[1]);
  if (!value) return undefined;

  if (bytes) {
    const bits = bytes * 8;
    const expected = bits / 6;
    return `${value}개 문자는 후보 변환 결과다. Radix-64는 ${bytes}바이트를 ${bits}비트로 보고 6비트 단위로 나누므로 패드 문자를 제외하면 ${expected}개 문자가 된다.`;
  }

  const encodedChars = Number(questionPrompt.match(/(\d+)\s*개의 문자/)?.[1]);
  if (!encodedChars) return undefined;

  const expectedBytes = (encodedChars * 6) / 8;
  return `${value}바이트는 후보 원문 크기다. Radix-64 결과 ${encodedChars}개 문자는 ${encodedChars * 6}비트이므로 패드 문자를 제외하면 원문 크기는 ${expectedBytes}바이트가 된다.`;
}

function describeScytaleChoice(choiceText: string, questionPrompt: string) {
  const text = normalizeSecurityChoiceText(choiceText);
  if (!/스파르타의 봉 암호/.test(questionPrompt) || !/^\d{8}$/.test(text)) return undefined;

  if (text === "12348765") {
    return "12348765는 앞부분이 평문 순서를 그대로 유지하고 뒤쪽 일부만 뒤바뀐 형태라 봉에 감아 일정 간격으로 읽는 전치 규칙의 암호문으로 보기 어렵다.";
  }

  return `${text}는 같은 문자 집합을 위치만 재배열한 전치 암호 후보로, 봉의 둘레와 감는 방식에 따라 만들 수 있는 배열이다.`;
}

function describeIPv4Choice(choiceText: string, questionPrompt: string) {
  if (!/IPv4/.test(questionPrompt)) return undefined;

  const text = normalizeSecurityChoiceText(choiceText);
  if (/Class [A-D]/.test(text)) {
    const firstOctet = Number(questionPrompt.match(/\n(\d{1,3})\./)?.[1]);
    if (!firstOctet) return undefined;
    const expectedClass =
      firstOctet < 128 ? "Class A" : firstOctet < 192 ? "Class B" : firstOctet < 224 ? "Class C" : "Class D";
    return `${text}는 IPv4 주소 클래스 후보다. 첫 옥텟 ${firstOctet}은 ${expectedClass} 범위에 해당한다.`;
  }

  if (/hostid/.test(questionPrompt)) {
    const expectedHostId = "13";
    return `${text}는 hostid 후보다. 주소 211.46.136.13은 Class C 범위이므로 hostid는 마지막 1바이트인 ${expectedHostId}이다.`;
  }

  return undefined;
}

export function buildSecurityChoiceExplanation({
  choiceText,
  isCorrect,
  questionPrompt,
  topicConcept,
  topicBasis,
  textbook,
}: {
  choiceText: string;
  isCorrect: boolean;
  questionPrompt: string;
  topicConcept: string;
  topicBasis: string;
  textbook: string;
}) {
  const normalizedChoice = normalizeSecurityChoiceText(choiceText);
  const choiceConcept =
    describeRadixChoice(choiceText, questionPrompt) ??
    describeScytaleChoice(choiceText, questionPrompt) ??
    describeIPv4Choice(choiceText, questionPrompt) ??
    describeTerm(choiceText);
  const source = `강의 내용 기준: ${topicBasis} 교재 개념 기준: ${textbook}.`;
  const exceptionPrompt = isExceptionPrompt(questionPrompt);
  const marked = markedChoice(normalizedChoice);

  if (isCorrect) {
    return {
      verdict: "correct" as ChoiceVerdict,
      reason: [
        `정답 근거: ${choiceConcept || topicBasis}`,
        exceptionPrompt
          ? `${marked} 문항이 찾는 예외에 해당한다.`
          : `${marked} ${topicConcept} 문항에서 요구한 조건과 일치한다.`,
      ].join(" "),
      conceptBasis: source,
    };
  }

  const wrongBasis =
    choiceConcept ||
    `「${normalizedChoice}」는 강의·교재에서 ${topicConcept}의 핵심 조건으로 제시되지 않는다.`;

  return {
    verdict: "wrong" as ChoiceVerdict,
    reason: [
      `오답 근거: ${wrongBasis}`,
      exceptionPrompt
        ? `${marked} 문항이 찾는 예외가 아니다.`
        : `${marked} ${topicConcept} 문항의 정답 조건에 해당하지 않는다.`,
    ].join(" "),
    conceptBasis: source,
  };
}
