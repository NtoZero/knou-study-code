import type { QuizItem } from "@/components/dlShared/Quiz";

function question(
  q: string,
  answer: number,
  examSkill: string,
  basis: string,
  slides: string,
  choices: [string, string][],
): QuizItem {
  return {
    q,
    answer,
    examSkill,
    basis,
    source: "변형",
    refs: { slides },
    choices: choices.map(([text, reason], i) => ({
      text,
      isCorrect: i === answer,
      explanation: { basis, reason },
    })),
  };
}

