const listText = (items?: string[]) => items?.filter(Boolean).join(" / ") ?? "";

const conceptTableRows = (unit: SoftwareLectureContent["units"][number]) => {
  const procedureText = listText(unit.procedure);
  const contrastText = listText(unit.contrast);
  const conditionBasis = unit.formula ?? (procedureText || contrastText || unit.why);
  const conditionCheck = unit.contrast?.[0] ?? unit.procedure?.[0] ?? unit.examFocus;

  return [
    {
      criterion: "정의",
      lectureBasis: unit.definition,
      examCheck: unit.examFocus,
    },
    {
      criterion: "구성요소",
      lectureBasis: listText(unit.components),
      examCheck: `${unit.title} 보기에서 구성요소가 빠지거나 다른 개념의 요소가 섞였는지 확인`,
    },
    {
      criterion: unit.formula ? "공식·표기" : "절차·조건",
      lectureBasis: conditionBasis,
      examCheck: conditionCheck,
    },
    {
      criterion: "비교·오답 경계",
      lectureBasis: contrastText || unit.mistake,
      examCheck: unit.mistake,
    },
  ];
};

const withConceptTables = (units: SoftwareLectureContent["units"]) =>
  units.map((unit) => ({
    ...unit,
    tableRows: unit.tableRows ?? conceptTableRows(unit),
  }));

const richQuizzes = (units: SoftwareLectureContent["units"]): SoftwareLectureContent["quizzes"] =>
  units.slice(0, 5).map((unit, index) => {
    const distractors = units
      .filter((candidate) => candidate.title !== unit.title)
      .slice(0, 3);
    const basis = `근거: ${unit.definition}`;
    return {
      q: `${unit.title}: 시험 문항에서 가장 먼저 확인할 기준은?`,
      category: unit.title,
      basis,
      examSkill: unit.examFocus,
      choices: [
        choice(unit.examFocus, true, basis, `오답 기준: ${unit.mistake}`),
        ...distractors.map((candidate) =>
          choice(
            candidate.examFocus,
            false,
            basis,
            `오답 기준: 이 보기는 ${candidate.title}의 판단 기준에 가깝고, ${unit.title} 문항의 핵심 조건과 다르다.`,
          ),
        ),
      ],
    };
  });

