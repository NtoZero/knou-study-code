function buildQuestion(question: RawQuestion): SecurityPastExamQuestion {
  const topic = securityPastExamTopics[question.topic];
  const embeddedChoices = extractEmbeddedChoiceMap(question.prompt);

  return {
    id: `security-${question.year}-${question.number}`,
    year: question.year,
    semester: "1",
    examName: `${question.year}학년도 1학기 기말시험`,
    number: question.number,
    prompt: question.prompt,
    choices: question.choices.map((text, index) => {
      const key = String(index + 1) as SecurityChoiceKey;
      const isCorrect = key === question.correctChoice;
      const expandedText = expandEmbeddedChoice(text, embeddedChoices);
      return {
        key,
        label: choiceLabels[key],
        text: expandedText,
        explanation: buildSecurityChoiceExplanation({
          choiceText: expandedText,
          isCorrect,
          questionPrompt: question.prompt,
          topicConcept: topic.concept,
          topicBasis: topic.basis,
          textbook: topic.textbook,
        }),
      };
    }),
    correctChoice: question.correctChoice,
    lectureRefs: [
      {
        lectureId: topic.lectureId,
        label: topic.lectureLabel,
        href: `/security/lecture/${topic.lectureId}`,
        concept: topic.concept,
      },
    ],
    conceptTags: Array.from(new Set([...(question.tags ?? []), ...topic.tags])).slice(0, 4),
    basis: topic.basis,
    examSkill: question.examSkill ?? topic.examSkill,
  };
}

export const securityPastExamQuestions = rawQuestions.map(buildQuestion);

export const securityPastExamTopicEntries = Object.entries(securityPastExamTopics).map(([key, value]) => ({
  key: key as TopicKey,
  ...value,
}));
