function extractEmbeddedChoiceMap(prompt: string) {
  const entries = Array.from(prompt.matchAll(/^([가-힣])\.\s+(.+)$/gm));
  return Object.fromEntries(entries.map(([, key, value]) => [key, value.trim()]));
}

function expandEmbeddedChoice(choiceText: string, embeddedChoices: Record<string, string>) {
  const trimmed = choiceText.trim();
  const embedded = embeddedChoices[trimmed];
  return embedded ? `${trimmed}. ${embedded}` : choiceText;
}

