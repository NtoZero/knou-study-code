/** 직선 w1·x1 + w2·x2 + b = 0 으로 표현되는 결정경계 */
export interface Boundary {
  w1: number;
  w2: number;
  b: number;
}

/** 단위 계단 함수를 쓴 퍼셉트론의 출력: u ≥ 0 이면 1, 아니면 0 */
export function perceptronOut(bd: Boundary, x1: number, x2: number): 0 | 1 {
  return bd.w1 * x1 + bd.w2 * x2 + bd.b >= 0 ? 1 : 0;
}

/** target 종류를 1, 나머지를 0으로 둔 레이블 — prepare_data(target)가 만드는 레이블과 같다 */
export function irisLabels(target: IrisSpecies): (0 | 1)[] {
  const ti = irisSpecies.indexOf(target);
  return irisPetals.map(([, , s]) => (s === ti ? 1 : 0));
}

/** 학습표본 150개 가운데 이 경계가 맞춘 개수 */
export function countCorrect(bd: Boundary, target: IrisSpecies): number {
  const labels = irisLabels(target);
  return irisPetals.reduce(
    (acc, [x1, x2], i) => acc + (perceptronOut(bd, x1, x2) === labels[i] ? 1 : 0),
    0,
  );
}
